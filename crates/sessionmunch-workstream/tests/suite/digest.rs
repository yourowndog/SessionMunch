#[test]
fn shell_writes_are_file_touches_but_heredoc_bodies_and_stream_redirects_are_not() {
    let mut events = Vec::new();
    events.extend(bash("sed -i 's/a/b/' src/lib.rs", "", false));
    events.extend(bash(
        "cat > notes.md <<'EOF'\n> quoted line > not-a-file\nEOF",
        "",
        false,
    ));
    events.extend(bash(
        "echo X=1 >> .env && grep -q y f 2>/dev/null",
        "",
        false,
    ));
    events.extend(bash("printf x | tee -a log/out.txt", "", false));
    events.extend(bash("rm -f old.txt", "", false));
    events.extend(bash(
        "sudo install -m 0644 a.json /etc/app/a.json",
        "",
        false,
    ));
    // Scratch output, loop variables and unexpanded paths are not outcomes.
    events.extend(bash(
        "echo 1 > /tmp/probe.txt; for x in a b; do rm x; done; cp a \"$OUT/b\"",
        "",
        false,
    ));
    // A failed command proves nothing about the file.
    events.extend(bash(
        "sed -i 's/x/y/' broken.rs",
        "Exit code 2\nsed: no such file",
        true,
    ));
    let digest = claude(events);
    let touched: Vec<(String, String)> = digest
        .of(FactKind::FileTouch)
        .map(|f| {
            (
                f.payload["path"].as_str().unwrap_or_default().into(),
                f.payload["verb"].as_str().unwrap_or_default().into(),
            )
        })
        .collect();
    assert_eq!(
        touched,
        vec![
            ("src/lib.rs".into(), "edit".into()),
            ("notes.md".into(), "write".into()),
            (".env".into(), "append".into()),
            ("log/out.txt".into(), "write".into()),
            ("old.txt".into(), "delete".into()),
            ("/etc/app/a.json".into(), "write".into()),
        ]
    );
    assert!(
        digest
            .of(FactKind::FileTouch)
            .all(|f| f.payload["via"] == "shell")
    );
}

#[test]
fn edit_tools_and_patches_are_file_touches_deduplicated_by_path() {
    let patch = "*** Begin Patch\n*** Update File: app/Main.kt\n@@\n-a\n+b\n*** Add File: app/New.kt\n+x\n*** End Patch";
    let digest = claude(vec![
        call(
            "Edit",
            &json!({"file_path": "/r/src/a.rs", "old_string": "x", "new_string": "y"}),
        ),
        result("ok", Some(false)),
        call(
            "Write",
            &json!({"file_path": "/r/src/a.rs", "content": "z"}),
        ),
        result("ok", Some(false)),
        event(
            WorkstreamEventKind::ToolCall,
            "assistant",
            &format!("apply_patch: {patch}"),
            json!({"tool": "apply_patch"}),
        ),
        result("Success", None),
    ]);
    let paths = texts(&digest, FactKind::FileTouch, "path");
    assert_eq!(paths, vec!["/r/src/a.rs", "app/Main.kt", "app/New.kt"]);
    let first = digest.of(FactKind::FileTouch).next().expect("touch");
    assert_eq!(first.refs.len(), 2, "both edits cite the one path");
}

