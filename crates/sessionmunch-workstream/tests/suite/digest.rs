#[test]
fn ended_reads_only_the_last_event() {
    // Interrupted mid-session, then resumed and answered: clean.
    let resumed = claude(vec![
        user("do it"),
        user("[Request interrupted by user]"),
        user("now try again with the fix"),
        assistant("Fixed."),
    ]);
    assert_eq!(ended(&resumed), "clean");

    let interrupted = claude(vec![
        user("audit the hooks"),
        user("[Request interrupted by user]"),
    ]);
    assert_eq!(ended(&interrupted), "interrupted");

    let open = claude(vec![user("one"), assistant("ok"), user("what about two?")]);
    assert_eq!(ended(&open), "unknown");

    let limited = claude(vec![
        user("write the report"),
        assistant("Report written to REPORT.md."),
        assistant("You've hit your session limit · resets 7am"),
    ]);
    assert_eq!(ended(&limited), "usage_limit");
    assert_eq!(
        texts(&limited, FactKind::FinalReply, "text"),
        vec!["Report written to REPORT.md."],
        "the limit notice is not the final reply"
    );
}

#[test]
fn native_terminal_markers_override_but_not_for_an_unanswered_request() {
    let aborted = NativeSignals {
        terminal: Some(TerminalSignal {
            state: EndState::Interrupted,
            detail: "codex turn_aborted: interrupted".into(),
        }),
        ..NativeSignals::default()
    };
    let digest = digest_of(
        ManagedHarness::Codex,
        vec![user("go"), assistant("partial")],
        &aborted,
    );
    assert_eq!(ended(&digest), "interrupted");

    let complete_without_reply = NativeSignals {
        terminal: Some(TerminalSignal {
            state: EndState::Clean,
            detail: "codex task_complete".into(),
        }),
        ..NativeSignals::default()
    };
    let digest = digest_of(
        ManagedHarness::Codex,
        vec![user("one"), assistant("ok"), user("run yay -Syu")],
        &complete_without_reply,
    );
    assert_eq!(ended(&digest), "unknown");
}

#[test]
fn native_signals_take_the_last_codex_marker_and_claude_titles() {
    let dir = tempfile::tempdir().expect("tempdir");
    let codex = dir.path().join("rollout.jsonl");
    std::fs::write(
        &codex,
        [
            json!({"type": "event_msg", "payload": {"type": "turn_aborted", "reason": "interrupted"}}),
            json!({"type": "response_item", "payload": {"type": "message"}}),
            json!({"type": "event_msg", "payload": {"type": "task_complete", "last_agent_message": "done"}}),
        ]
        .map(|v| v.to_string())
        .join("\n"),
    )
    .expect("write");
    let signals = read_native_signals(ManagedHarness::Codex, &codex).expect("signals");
    let terminal = signals.terminal.expect("terminal");
    assert_eq!(terminal.state, EndState::Clean);

    let claude_file = dir.path().join("s.jsonl");
    std::fs::write(
        &claude_file,
        [
            json!({"type": "ai-title", "aiTitle": "Fix relay"}),
            json!({"type": "system", "subtype": "away_summary", "content": "Relay fixed; check thread."}),
        ]
        .map(|v| v.to_string())
        .join("\n"),
    )
    .expect("write");
    let signals = read_native_signals(ManagedHarness::Claude, &claude_file).expect("signals");
    assert_eq!(signals.title.as_deref(), Some("Fix relay"));
    assert_eq!(signals.recap.as_deref(), Some("Relay fixed; check thread."));
    assert_eq!(signals.terminal, None, "Claude records no terminal marker");
}

