#[test]
fn commits_come_from_git_output_quiet_commits_and_push_ranges() {
    let mut events = Vec::new();
    events.extend(bash(
        "git commit -m 'docs: note'",
        "[main 1a2b3c4] docs: note\n 1 file changed",
        false,
    ));
    events.extend(bash("git commit -q -m \"wip: checkpoint\"", "", false));
    events.extend(bash("git -C /r commit -qam 'chore: tidy'", "", false));
    events.extend(bash(
        "git commit -q -F - <<'EOF'\nfeat: from heredoc\n\nbody\nEOF",
        "",
        false,
    ));
    events.extend(bash(
        "git push origin main",
        "To github.com:o/r.git\n   1a2b3c4..5d6e7f8  main -> main",
        false,
    ));
    // Code-mode output arrives JSON-stringified with escaped newlines.
    events.push(call("exec", &json!("x")));
    events.push(result(
        "{\"output\":\"x\\n[feat/a 9abcdef] feat: thing\\n\"}",
        None,
    ));
    // ...or embedded in a JSON line after real newlines.
    events.push(call("exec", &json!("y")));
    events.push(result(
        "Script completed\n{\"output\":\"[main 7a7a7a7] ledger: record\\n\",\"exit_code\":0}",
        None,
    ));
    let digest = claude(events);
    let commits: Vec<(Value, Value, String)> = digest
        .of(FactKind::Commit)
        .map(|f| {
            (
                f.payload["sha"].clone(),
                f.payload["message"].clone(),
                f.payload["basis"].as_str().unwrap_or_default().into(),
            )
        })
        .collect();
    assert_eq!(
        commits,
        vec![
            (json!("1a2b3c4"), json!("docs: note"), "git_output".into()),
            (
                Value::Null,
                json!("wip: checkpoint"),
                "command_succeeded_without_output".into()
            ),
            (
                Value::Null,
                json!("chore: tidy"),
                "command_succeeded_without_output".into()
            ),
            (
                Value::Null,
                json!("feat: from heredoc"),
                "command_succeeded_without_output".into()
            ),
            (json!("9abcdef"), json!("feat: thing"), "git_output".into()),
            (
                json!("7a7a7a7"),
                json!("ledger: record"),
                "git_output".into()
            ),
        ]
    );
    assert_eq!(
        texts(&digest, FactKind::Push, "range"),
        vec!["1a2b3c4..5d6e7f8"]
    );
}

#[test]
fn unknown_exits_claim_neither_a_quiet_commit_nor_a_pass() {
    // A result with no exit and no error flag proves nothing about a commit.
    let mut events = vec![call(
        "Bash",
        &json!({"command": "git commit -q -m 'wip: maybe'"}),
    )];
    events.push(result("", None));
    // Kimi/Kiro emit a null error flag when the harness reported none.
    events.push(call("Bash", &json!({"command": "cargo build"})));
    let mut unknown = result("BUILD FAILED", None);
    unknown.metadata = json!({"is_error": null});
    events.push(unknown);
    let digest = claude(events);
    assert_eq!(digest.of(FactKind::Commit).count(), 0);
    let exits: Vec<Value> = digest
        .of(FactKind::Command)
        .map(|f| f.payload["exit"].clone())
        .collect();
    assert!(!exits.contains(&json!(0)), "{exits:?}");
}

