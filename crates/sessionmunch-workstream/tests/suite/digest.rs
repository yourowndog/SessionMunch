#[test]
fn results_pair_by_id_when_only_the_call_kept_one() {
    // Hermes keeps call ids on calls but not on results.
    let mut first = call("terminal", &json!({"command": "make"}));
    first.metadata = json!({"tool": "terminal", "call_id": "a"});
    let mut second = event(
        WorkstreamEventKind::ToolCall,
        "assistant",
        "write_file {\"path\": \"/r/notes.md\", \"content\": \"x\"}",
        json!({"tool": "write_file", "call_id": "b"}),
    );
    second.metadata["tool"] = json!("write_file");
    let digest = claude(vec![
        first,
        result("{\"output\": \"\", \"exit_code\": 2}", None),
        second,
        result("ok", None),
    ]);
    assert_eq!(digest.unpaired_results, 0);
    let exits: Vec<Value> = digest
        .of(FactKind::Command)
        .map(|f| f.payload["exit"].clone())
        .collect();
    assert_eq!(exits, vec![json!(2)]);
    assert_eq!(
        texts(&digest, FactKind::FileTouch, "path"),
        vec!["/r/notes.md"]
    );
}

