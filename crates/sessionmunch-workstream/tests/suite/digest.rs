//! Deterministic session digest: fact extraction and card rendering over
//! small synthetic transcripts.

use serde_json::{Value, json};
use sessionmunch_core::{AgentKind, NewWorkstreamEvent, WorkstreamEventKind};

use crate::digest::{
    EndState, FactKind, NativeSignals, SessionDigest, TerminalSignal, extract_transcript_facts,
    read_native_signals, render_card,
};
use crate::harness::ManagedHarness;
use crate::transcript::ExportedTranscript;

fn event(
    kind: WorkstreamEventKind,
    role: &str,
    content: &str,
    metadata: Value,
) -> NewWorkstreamEvent {
    NewWorkstreamEvent {
        event_id: format!("native:{content:.12}"),
        agent: AgentKind::ClaudeCode,
        native_session_id: "s1".into(),
        source_record_id: None,
        kind,
        role: Some(role.into()),
        content: content.into(),
        occurred_at: Some("2026-10-24T00:00:00Z".into()),
        metadata,
    }
}

fn user(text: &str) -> NewWorkstreamEvent {
    event(WorkstreamEventKind::Message, "user", text, json!({}))
}

fn assistant(text: &str) -> NewWorkstreamEvent {
    event(WorkstreamEventKind::Message, "assistant", text, json!({}))
}

fn call(tool: &str, input: &Value) -> NewWorkstreamEvent {
    event(
        WorkstreamEventKind::ToolCall,
        "assistant",
        &format!("{tool}: {input}"),
        json!({"tool": tool}),
    )
}

fn result(text: &str, is_error: Option<bool>) -> NewWorkstreamEvent {
    let metadata = is_error.map_or_else(|| json!({}), |flag| json!({"is_error": flag}));
    event(WorkstreamEventKind::ToolResult, "tool", text, metadata)
}

fn bash(command: &str, output: &str, is_error: bool) -> [NewWorkstreamEvent; 2] {
    [
        call("Bash", &json!({"command": command})),
        result(output, Some(is_error)),
    ]
}

fn digest_of(
    harness: ManagedHarness,
    events: Vec<NewWorkstreamEvent>,
    signals: &NativeSignals,
) -> SessionDigest {
    let transcript = ExportedTranscript {
        native_session_id: "s1".into(),
        source_cursor: None,
        events,
        losses: Vec::new(),
    };
    extract_transcript_facts(harness.as_str(), &transcript, signals)
}

fn claude(events: Vec<NewWorkstreamEvent>) -> SessionDigest {
    digest_of(ManagedHarness::Claude, events, &NativeSignals::default())
}

fn texts(digest: &SessionDigest, kind: FactKind, key: &str) -> Vec<String> {
    digest
        .of(kind)
        .map(|fact| fact.payload[key].as_str().unwrap_or_default().to_string())
        .collect()
}

fn ended(digest: &SessionDigest) -> String {
    digest
        .of(FactKind::Ended)
        .next()
        .expect("ended fact")
        .payload["state"]
        .as_str()
        .unwrap_or_default()
        .to_string()
}

#[test]
fn user_turns_split_into_requests_continuations_pastes_and_scaffolding() {
    let digest = claude(vec![
        user("<local-command-caveat>Caveat: generated by the user</local-command-caveat>"),
        user("<system-reminder>context</system-reminder>"),
        user("Fix the flaky upload test"),
        user("continue"),
        user("Check for updates."),
        user("/compact"),
        user("│bridge$ install ▕\n│[ℹ] building... ▕\n│[✘] Request failed with status code 400 ▐"),
        user(
            "<USER_REQUEST>\nship the theme browser upstream\n</USER_REQUEST>\n<ADDITIONAL_METADATA>local time</ADDITIONAL_METADATA>",
        ),
        // Prose typed into a TUI frame is still a request.
        user(
            "❯ The bot keeps renaming topics │\n│ instead of relaying the actual assistant messages to me │",
        ),
        user("[Request interrupted by user]"),
        assistant("done"),
    ]);
    assert_eq!(
        texts(&digest, FactKind::Request, "text"),
        vec![
            "Fix the flaky upload test".to_string(),
            "ship the theme browser upstream".to_string(),
            "The bot keeps renaming topics\ninstead of relaying the actual assistant messages to me".to_string(),
        ]
    );
    assert_eq!(digest.of(FactKind::Continuation).count(), 3);
    assert_eq!(
        texts(&digest, FactKind::PastedOutput, "first_line"),
        vec!["│bridge$ install ▕"]
    );
    assert_eq!(digest.scaffolding_dropped, 3);
    let pasted = digest.of(FactKind::PastedOutput).next().expect("pasted");
    assert_eq!(
        pasted.payload["folds_into"], 3,
        "folds into the request at e3"
    );
    let card = render_card(&digest);
    assert!(card.contains(
        "- Fix the flaky upload test (e3)\n  - with pasted output `│bridge$ install ▕` (e7)"
    ));
}

#[test]
fn commands_pair_with_results_and_report_how_the_exit_was_learned() {
    let mut events = Vec::new();
    events.extend(bash("ls", "a\nb", false));
    events.extend(bash("false", "Exit code 1\n", true));
    events.push(call("exec_command", &json!({"cmd": "make"})));
    events.push(result(
        "Chunk ID: 1\nProcess exited with code 2\nOutput:\n",
        None,
    ));
    events.push(call("shell", &json!({"command": ["bash", "-lc", "pwd"]})));
    events.push(result(
        "Exit code: 0\nWall time: 0 seconds\nOutput:\n/home",
        None,
    ));
    let digest = claude(events);
    let commands: Vec<(String, Value, String)> = digest
        .of(FactKind::Command)
        .map(|f| {
            (
                f.payload["command"].as_str().unwrap_or_default().into(),
                f.payload["exit"].clone(),
                f.payload["exit_basis"].as_str().unwrap_or_default().into(),
            )
        })
        .collect();
    assert_eq!(
        commands,
        vec![
            ("ls".into(), json!(0), "inferred_from_is_error_false".into()),
            ("false".into(), json!(1), "reported".into()),
            ("make".into(), json!(2), "reported".into()),
            ("pwd".into(), json!(0), "reported".into()),
        ]
    );
    assert_eq!(digest.unpaired_results, 0);
}

